#!/usr/bin/env node
// TEMPLATE — regenerates the retrieval indexes for a docs folder.
// One line per node: link | title | status | one sentence. Nothing else.
//
// To adapt: set CONTEXT to the vault folder, then edit GROUPS — one entry per
// index file, one section per subfolder. Everything below GROUPS is generic.
// Check the `status` and `summary` extractors against this repo's file format.
//
// Run: npm run graph:index   (or: npm run graph:index -- --check)

import { readdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs'
import { join, relative } from 'node:path'

const ROOT = new URL('..', import.meta.url).pathname.replace(/\/$/, '')
const CONTEXT = join(ROOT, 'CONTEXT')
const CHECK = process.argv.includes('--check')

/** A node whose status says the work is over. Anything else — including a node
 *  with no status at all — is treated as live, so nothing goes missing. */
const SETTLED = (n) => /^(shipped|cut|done|closed|wontfix|superseded)\b/.test(n.status)

const GROUPS = [
  { file: 'index.md', title: 'index — durable knowledge', sections: [
    { heading: 'Glossary', dir: '.', only: ['CONTEXT.md'] },
    { heading: 'Decisions (ADR)', dir: 'docs/adr' },
    { heading: 'Planning (PRDs, stack, scope)', dir: 'planning' },
  ]},
  // Work items accumulate. Once most of them are settled, an index holding all
  // of them costs more to load than grepping the folder it indexes — so live
  // and settled get their own files, and the router points at both.
  { file: 'index-issues.md', title: 'index — issues (open work)', sections: [
    { heading: 'Open issues', dir: 'issues', reject: SETTLED },
  ]},
  { file: 'index-issues-closed.md', title: 'index — issues (shipped & cut)', sections: [
    { heading: 'Settled issues', dir: 'issues', accept: SETTLED },
  ]},
  { file: 'index-handoffs.md', title: 'index — handoffs (session history)', sections: [
    { heading: 'Handoffs', dir: 'handoffs' },
  ]},
]

/** First `# ` heading, minus any leading number. */
function title(body, fallback) {
  const m = body.match(/^#\s+(.+)$/m)
  return m ? m[1].trim() : fallback.replace(/\.md$/, '')
}

/** `Status: shipped` or `- Status: Accepted` anywhere near the top. */
function status(body) {
  const m = body.slice(0, 800).match(/^-?\s*Status:\s*(.+)$/m)
  return m ? m[1].trim().toLowerCase() : ''
}

/**
 * First real sentence of prose: skip the heading, metadata lines, and any
 * `## Context`-style subheading, then take one sentence and cap its length.
 */
function summary(body) {
  const lines = body.split('\n')
  const prose = []
  for (const raw of lines) {
    const line = raw.trim()
    if (!line) { if (prose.length) break; else continue }
    if (line.startsWith('#')) { if (prose.length) break; else continue }
    if (/^-?\s*(Status|Date|Blocked by|Depends on|Owner|Verification-command):/i.test(line)) continue
    if (/^\((condensed|full spec)/i.test(line)) continue
    if (/^[-*|>]/.test(line)) continue
    prose.push(line)
  }
  let text = prose.join(' ').replace(/\s+/g, ' ')
  text = text.replace(/\*\*(.+?)\*\*/g, '$1').replace(/`(.+?)`/g, '$1')
  const dot = text.search(/\.\s/)
  if (dot > 30) text = text.slice(0, dot + 1)
  if (text.length > 150) text = text.slice(0, 147).replace(/\s\S*$/, '') + '…'
  return text || '(no summary)'
}

function nodesIn(section) {
  const dir = join(CONTEXT, section.dir)
  if (!existsSync(dir)) return []
  const names = section.only
    ? section.only.filter((n) => existsSync(join(dir, n)))
    : readdirSync(dir).filter((n) => n.endsWith('.md')).sort()
  const nodes = names.map((name) => {
    const body = readFileSync(join(dir, name), 'utf8')
    const link = relative(CONTEXT, join(dir, name))
    return { name, link, title: title(body, name), status: status(body), summary: summary(body) }
  })
  if (section.accept) return nodes.filter(section.accept)
  if (section.reject) return nodes.filter((n) => !section.reject(n))
  return nodes
}

function render(group) {
  const out = [`# ${group.title}`, '', '<!-- GENERATED by scripts/build-graph-index.mjs — do not hand-edit. -->', '']
  for (const section of group.sections) {
    const nodes = nodesIn(section)
    if (!nodes.length) continue
    out.push(`## ${section.heading} (${nodes.length})`, '')
    for (const n of nodes) {
      const tag = n.status ? ` [${n.status}]` : ''
      out.push(`- [[${n.link}|${n.title}]]${tag} — ${n.summary}`)
    }
    out.push('')
  }
  return out.join('\n')
}

let drift = 0
for (const group of GROUPS) {
  const path = join(CONTEXT, group.file)
  const next = render(group)
  const prev = existsSync(path) ? readFileSync(path, 'utf8') : ''
  if (prev === next) continue
  if (CHECK) {
    console.error(`stale: CONTEXT/${group.file}`)
    drift++
  } else {
    writeFileSync(path, next)
    console.log(`wrote CONTEXT/${group.file}`)
  }
}

if (CHECK && drift) {
  console.error(`\n${drift} index file(s) stale. Run: npm run graph:index`)
  process.exit(1)
}
if (CHECK) console.log('indexes current')
